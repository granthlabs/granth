/**
 * Snapshot the identifiers the published docs mention.
 *
 * The docs live in the SITE repo since the split, but the coverage gate has to
 * stay in THIS repo: an undocumented public member first caught by the site's CI
 * would already be on npm. Reading them over the network on every `npm test` was
 * the obvious way to have both, and it was wrong — it made the suite fail
 * offline and let an edit in another repo turn this one's CI red with no code
 * change. It produced exactly one false failure during a release before anyone
 * noticed.
 *
 * So the network read moved here, to a deliberate act, and the test reads a
 * committed file. Same failure caught at the same moment, minus the coupling.
 *
 *   npm run docs:refresh     # after documenting something in the site repo
 *
 * Only identifier-shaped tokens are kept, not the prose: the gate asks one
 * question — "is this name mentioned anywhere?" — and that is all it needs to
 * answer it for a name that does not exist yet.
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../packages/core/client/docs-surface.json'
);
const REPO = 'granthlabs/granthlabs.github.io';
const API = `https://api.github.com/repos/${REPO}`;

const listing = await fetch(`${API}/contents/docs`);
if (!listing.ok) throw new Error(`cannot list ${REPO}/docs (${listing.status})`);
const files = (await listing.json()).filter((f) => f.name.endsWith('.md'));
if (!files.length) throw new Error(`${REPO}/docs returned no markdown`);

const head = await fetch(`${API}/commits/main`).then((r) => (r.ok ? r.json() : null));

const bodies = await Promise.all(
  files.map((f) =>
    fetch(f.download_url).then((r) => {
      if (!r.ok) throw new Error(`cannot read ${f.name} (${r.status})`);
      return r.text();
    })
  )
);

// `$` is deliberate: generated columns and shadow tables use it in identifiers.
const names = [...new Set(bodies.join('\n').match(/[A-Za-z_$][\w$]*/g) ?? [])].sort();

writeFileSync(
  OUT,
  JSON.stringify(
    {
      _comment: `Generated by scripts/refresh-docs-surface.mjs from ${REPO}/docs. Do not hand-edit — run: npm run docs:refresh`,
      source: REPO,
      sha: head?.sha ?? null,
      files: files.map((f) => f.name).sort(),
      names,
    },
    null,
    2
  ) + '\n'
);

console.log(
  `docs-surface.json: ${names.length} identifiers from ${files.length} files` +
    (head?.sha ? ` @ ${head.sha.slice(0, 7)}` : '')
);
